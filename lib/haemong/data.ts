export function searchKeywords(query: string): string[] {
  const q = query.trim();
  if (!q) return [];
  return Object.keys(DREAMS).filter(k =>
    k.includes(q) ||
    DREAMS[k].summary.includes(q) ||
    DREAMS[k].tags.some(t => t.includes(q))
  );
}

