export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { phone, email, name1, birthYear1, birthMonth1, birthDay1, gender1,
            name2, birthYear2, birthMonth2, birthDay2, gender2 } = body;
    const marketing = body.marketing === true;
    const loveStyle: "E" | "S" | "균형" = body.loveStyle === "E" || body.loveStyle === "S" ? body.loveStyle : "균형";

    if (!birthYear1 || !birthYear2) {
      return NextResponse.json({ error: "생년월일을 입력해주세요" }, { status: 400 });
    }

    const oh1 = getOh(Number(birthYear1));
    const oh2 = getOh(Number(birthYear2));
    const score = getScore(oh1, oh2, Number(birthMonth1||1), Number(birthDay1||1), Number(birthMonth2||1), Number(birthDay2||1));
    const grade = getGrade(score);
    const content = getContent(oh1, oh2);
    const mbti1 = getMbtiHint(oh1);
    const mbti2 = getMbtiHint(oh2);

    const result = {
      phone: phone || "",
      email: email || "",
      marketing,
      name: name1 || "나",
      name1: name1 || "나", birthYear1, birthMonth1, birthDay1, gender1,
      name2: name2 || "상대방", birthYear2, birthMonth2, birthDay2, gender2,
      oh1, oh2, score, grade, mbti1, mbti2, loveStyle,
      ...content,
      createdAt: Date.now(),
    };

    const ref = await db.ref("gunghap_analyses").push(result);
    return NextResponse.json({ id: ref.key, result });
  } catch (e) {
    console.error(e);
    return NextResponse.json({ error: "분석 중 오류가 발생했습니다" }, { status: 500 });
  }
}

export async function GET(request: NextRequest) {
  try {
    const id = new URL(request.url).searchParams.get("id");
    if (!id) return NextResponse.json({ error: "id 없음" }, { status: 400 });
    const snap = await db.ref(`gunghap_analyses/${id}`).once("value");
    if (!snap.exists()) return NextResponse.json({ error: "결과 없음" }, { status: 404 });
    return NextResponse.json({ result: snap.val() });
  } catch (e) {
    return NextResponse.json({ error: "오류" }, { status: 500 });
  }
}
